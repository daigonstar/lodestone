#!/usr/bin/env python3
"""Make comms/app/ui/emoji.js, the emoji picker's list, from Unicode's emoji-test.txt.

Download the data file yourself (https://unicode.org/Public/emoji/latest/emoji-test.txt), then:
    python3 comms/tools/gen-emoji.py emoji-test.txt comms/app/ui/emoji.js
Only fully-qualified emoji are kept, without skin-tone variants (the picker offers the default ones).
"""
import json
import re
import sys

src, out = sys.argv[1], sys.argv[2]
groups, version = [], "?"
for line in open(src, encoding="utf-8"):
    if line.startswith("# Version:"):
        version = line.split(":", 1)[1].strip()
    m = re.match(r"# group: (.+)", line)
    if m:
        name = m.group(1).strip()
        groups.append([name, []])
        continue
    if line.startswith("#") or ";" not in line or "fully-qualified" not in line.split("#")[0]:
        continue
    codes = line.split(";")[0].split()
    if any(0x1F3FB <= int(c, 16) <= 0x1F3FF for c in codes):
        continue  # skin tones
    emoji = "".join(chr(int(c, 16)) for c in codes)
    name = re.sub(r"^.*?E\d+\.\d+\s+", "", line.split("#", 1)[1]).strip()
    groups[-1][1].append([emoji, name])
groups = [g for g in groups if g[0] != "Component" and g[1]]
total = sum(len(g[1]) for g in groups)
with open(out, "w", encoding="utf-8") as f:
    f.write(f"// Emoji for the picker: {total} emoji from Unicode emoji {version} (emoji-test.txt).\n")
    f.write("// Generated by comms/tools/gen-emoji.py. Unicode data © Unicode, Inc., under the Unicode License v3.\n")
    f.write('"use strict";\nconst EMOJI = ')
    json.dump(groups, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(f"{out}: {total} emoji in {len(groups)} groups (Unicode {version})")
